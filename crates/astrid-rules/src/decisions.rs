//! Decision cards and trade-off grids — the two markdown shapes a comment draws richly.
//!
//! A comment can ask a question as a *Decision*: a bold `**Decision:**` paragraph followed by a
//! list of marked options, which a shell draws as cards a reader taps instead of typing an answer.
//! A table whose body cells all lead with a rating (`++`, `~`, `🔴`) is a *trade-off grid*, which a
//! shell draws coloured. Anything that is not exactly one of these two shapes stays plain markdown.
//!
//! **Ported from `astrid-web/lib/comment-formats.ts`**, which is the source of truth, with
//! `contracts/fixtures/decisions.json` as the specification — generated by running that file over a
//! fixed case set, so a change to web's recogniser fails this crate's `decisions_contract` test.
//! The reference recogniser on Apple is `astrid-ios`
//! `Packages/AstridCore/Sources/AstridCore/Decision.swift`; the format itself is
//! `astrid-web/docs/PRODUCT_CONTRACT.md` §8, taught in `docs/DECISIONS.md`.
//!
//! The rule was implemented twice before this — Swift (280 LOC) and TypeScript (231) — and Android,
//! Windows and VS Code would each have written a third, fourth and fifth copy (task efae6297).
//! Not to be confused with [`crate`]'s unrelated namesake in `astrid_core::external::decisions`,
//! which is what an external-sync pass decides about a remote item.
//!
//! **No regex crate, on purpose.** This crate builds for `wasm32-unknown-unknown` and the browser
//! downloads it, so the patterns are hand-rolled against the TypeScript they mirror — alternative
//! by alternative, in the order it tries them, lookaheads included. Where that order matters it is
//! said so at the code.

use serde::Serialize;

// ---------------------------------------------------------------------------------------------
// Ratings
// ---------------------------------------------------------------------------------------------

/// What a rating token means: the word for it, and where it sits worst-to-best.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RatingStyle {
    /// The key a shell translates: `tasks.tradeoffRatings.<labelKey>` on web.
    pub label_key: &'static str,
    /// The English word, for a shell with no translation of it yet.
    pub label: &'static str,
    /// 0 (worst) to 4 (best). The key is drawn in this order, as Apple draws it; it is NOT the
    /// order of [`RATINGS`], which is the order the tokens are *parsed* in.
    pub rank: u8,
}

const fn style(label_key: &'static str, label: &'static str, rank: u8) -> RatingStyle {
    RatingStyle {
        label_key,
        label,
        rank,
    }
}

/// Every rating token, **in the order [`parse_rating`] tries them** — the TypeScript's
/// `--|-|~|\+\+|\+|🔴|🟡|🟢`. Longest first within a family, so `--` is never read as `-` and `++`
/// never as `+`. Sort by [`RatingStyle::rank`] to draw the key.
pub const RATINGS: &[(&str, RatingStyle)] = &[
    ("--", style("veryPoor", "Very poor", 0)),
    ("-", style("poor", "Poor", 1)),
    ("~", style("mixed", "Mixed", 2)),
    ("++", style("veryGood", "Very good", 4)),
    ("+", style("good", "Good", 3)),
    ("🔴", style("poor", "Poor", 1)),
    ("🟡", style("mixed", "Mixed", 2)),
    ("🟢", style("good", "Good", 3)),
];

/// The five rating words, worst to best — web's `RATING_LABEL_KEYS`.
pub const RATING_LABEL_KEYS: [&str; 5] = ["veryPoor", "poor", "mixed", "good", "veryGood"];

/// What one rating token means, or `None` for anything that is not one.
pub fn rating_style(token: &str) -> Option<RatingStyle> {
    RATINGS
        .iter()
        .find(|(candidate, _)| *candidate == token)
        .map(|(_, style)| *style)
}

/// One row of the key a shell draws beside a grid.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RatingEntry {
    pub token: &'static str,
    pub label_key: &'static str,
    pub label: &'static str,
    pub rank: u8,
}

/// Every token and what it means, for a shell drawing the key. Ordered by [`RatingStyle::rank`],
/// then by token, so the key reads worst to best however [`RATINGS`] is ordered for parsing.
pub fn rating_key() -> Vec<RatingEntry> {
    let mut entries: Vec<RatingEntry> = RATINGS
        .iter()
        .map(|(token, style)| RatingEntry {
            token,
            label_key: style.label_key,
            label: style.label,
            rank: style.rank,
        })
        .collect();
    entries.sort_by(|a, b| a.rank.cmp(&b.rank).then_with(|| a.token.cmp(b.token)));
    entries
}

/// A cell's leading rating and the words after it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Rating {
    pub rating: String,
    pub rest: String,
}

/// Split a leading rating token off a cell's text.
///
/// The token must be followed by whitespace or end the cell — the TypeScript's `(?=\s|$)` — so
/// `++cheap` carries no rating at all. An alternation falls through to the next token when its
/// lookahead fails rather than giving up, which is why `+` is tried after `++`.
pub fn parse_rating(cell: &str) -> Option<Rating> {
    let text = cell.trim();
    for (token, _) in RATINGS {
        if let Some(rest) = text.strip_prefix(*token) {
            if rest.is_empty() || rest.starts_with(char::is_whitespace) {
                return Some(Rating {
                    rating: (*token).to_string(),
                    rest: rest.trim().to_string(),
                });
            }
        }
    }
    None
}

// ---------------------------------------------------------------------------------------------
// Trade-off grids
// ---------------------------------------------------------------------------------------------

/// Is this table a trade-off grid?
///
/// Every non-empty body cell after the first column must carry a rating, at least one must exist,
/// and a table of bare `-` placeholders does not count — that is somebody's empty template, not a
/// judgement about anything.
pub fn is_tradeoff_grid(rows: &[Vec<String>]) -> bool {
    let mut rated = 0usize;
    let mut all_bare_dash = true;
    for row in rows {
        for cell in row.iter().skip(1) {
            if cell.trim().is_empty() {
                continue;
            }
            let Some(rating) = parse_rating(cell) else {
                return false;
            };
            rated += 1;
            if !(rating.rating == "-" && rating.rest.is_empty()) {
                all_bare_dash = false;
            }
        }
    }
    rated > 0 && !all_bare_dash
}

/// A table read as a grid, in one answer: whether it is one, what each body cell rates, and each
/// row's option name. Everything a shell needs to draw it, decided here rather than per shell.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Grid {
    pub is_grid: bool,
    /// Per row, the cells after the first column; `None` for one that carries no rating, which
    /// includes an empty cell.
    pub cells: Vec<Vec<Option<Rating>>>,
    /// Per row, the first column without the marker its writer put in front.
    pub row_names: Vec<String>,
}

/// Read a table's body rows as a grid. `rows` is each body row's cell text, first column included.
pub fn read_grid(rows: &[Vec<String>]) -> Grid {
    Grid {
        is_grid: is_tradeoff_grid(rows),
        cells: rows
            .iter()
            .map(|row| {
                row.iter()
                    .skip(1)
                    .map(|cell| parse_rating(cell))
                    .collect::<Vec<_>>()
            })
            .collect(),
        row_names: rows
            .iter()
            .map(|row| row.first().map(|cell| row_name(cell)).unwrap_or_default())
            .collect(),
    }
}

/// A grid row's option name without the marker its writer put in front (`A. Lisbon` → `Lisbon`);
/// the grid numbers its rows itself, as the cards do.
pub fn row_name(text: &str) -> String {
    match row_marker_len(text) {
        Some(len) => text[len..].trim().to_string(),
        None => text.trim().to_string(),
    }
}

/// The byte length of a leading row marker — `A. `, `2) `, `C: `, or a marker standing alone
/// (`B`) — the TypeScript's `^\s*(?:[A-Za-z]|\d{1,2})(?:[.):](?:\s+|$)|\s*$)`.
///
/// `\d{1,2}` is greedy and then backtracks, so `12. Twelve` takes both digits while `1. Go` takes
/// the one there is. A marker with no space after it is not a marker: `A.Lisbon` is a name.
fn row_marker_len(text: &str) -> Option<usize> {
    let body = text.trim_start();
    let leading = text.len() - body.len();
    for &marker in marker_lengths(body)? {
        let rest = &body[marker..];
        // `[.):]` then whitespace or the end of the text.
        if let Some(after) = rest.strip_prefix(['.', ')', ':']) {
            if after.is_empty() {
                return Some(leading + marker + 1);
            }
            let tail = after.trim_start();
            if tail.len() < after.len() {
                return Some(leading + marker + 1 + (after.len() - tail.len()));
            }
        }
        // Or the marker alone, `\s*$`: the match runs to the end, so the name is empty.
        if rest.trim().is_empty() {
            return Some(text.len());
        }
    }
    None
}

/// The byte length of a leading marker followed by its punctuation and then space or the end —
/// the web's `PUNCTUATED_MARKER`, `^\s*(?:[A-Za-z]|\d{1,2})[.):](?:\s+|$)`, which
/// `markdown::render` uses to drop a grid row's marker from its runs (AWTD-1626).
pub(crate) fn punctuated_marker_len(text: &str) -> Option<usize> {
    let body = text.trim_start();
    let leading = text.len() - body.len();
    for &marker in marker_lengths(body)? {
        let Some(after) = body[marker..].strip_prefix(['.', ')', ':']) else {
            continue;
        };
        let tail = after.trim_start();
        if after.is_empty() || tail.len() < after.len() {
            return Some(leading + marker + 1 + (after.len() - tail.len()));
        }
    }
    None
}

/// Is this text a marker and nothing else — the web's `BARE_MARKER`,
/// `^\s*(?:[A-Za-z]|\d{1,2})[.):]?\s*$` (AWTD-1626)?
pub(crate) fn is_bare_marker(text: &str) -> bool {
    let body = text.trim();
    let Some(lengths) = marker_lengths(body) else {
        return false;
    };
    lengths.iter().any(|&marker| {
        let rest = &body[marker..];
        rest.is_empty() || matches!(rest, "." | ")" | ":")
    })
}

/// The marker lengths to try at the start of `body`, longest first: two digits then one, or the
/// single letter there is. `None` when it starts with neither.
fn marker_lengths(body: &str) -> Option<&'static [usize]> {
    /// `\d{1,2}` is greedy and then backtracks, so two digits are tried before one.
    const TWO_THEN_ONE: &[usize] = &[2, 1];
    const ONE: &[usize] = &[1];

    let digits = body.chars().take_while(char::is_ascii_digit).count();
    if digits >= 2 {
        return Some(TWO_THEN_ONE);
    }
    // One digit, or the single letter — either way there is only one length to try.
    (digits == 1 || body.chars().next().is_some_and(|c| c.is_ascii_alphabetic())).then_some(ONE)
}

/// The letter over a grid's criterion column, from 0: A … Z, then AA, AB, as a spreadsheet does.
pub fn column_letter(index: u32) -> String {
    let mut name = String::new();
    let mut i = i64::from(index);
    while i >= 0 {
        name.insert(0, char::from(b'A' + (i % 26) as u8));
        i = i / 26 - 1;
    }
    name
}

