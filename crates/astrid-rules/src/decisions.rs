/// One option a Decision offers.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct DecisionOption {
    /// The marker as the asker wrote it, upper case: `A`, or `1`. A reply leading with it still
    /// chooses this option, whatever number it ended up with.
    pub letter: String,
    /// Its place in the list, from 1 — what the card shows and what [`reply`] leads with.
    pub number: u32,
    pub text: String,
    pub recommended: bool,
}

/// A comment read as a Decision.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Decision {
    /// The markdown before the `Decision:` paragraph.
    pub before: String,
    /// The paragraph after the bold `Decision:` label.
    pub prompt: String,
    pub options: Vec<DecisionOption>,
    /// The markdown after the option list.
    pub after: String,
}

/// Read a comment body as a Decision, or `None` when it is not exactly that shape.
///
/// Fewer than two options is not a question, an item without a bold marker means the list is prose,
/// and a Decision drawn as code is somebody *explaining* the format — all three stay plain markdown.
pub fn parse(content: &str) -> Option<Decision> {
    if content.is_empty() {
        return None;
    }
    let lines: Vec<&str> = content.split('\n').collect();
    let code = code_lines(&lines);
    let head_index =
        (0..lines.len()).find(|&i| !code[i] && decision_head(lines[i].trim()).is_some())?;

    let mut prompt_lines = vec![decision_head(lines[head_index].trim())?.to_string()];
    let mut i = head_index + 1;
    // The paragraph runs to the first blank line or list item.
    while i < lines.len() && !lines[i].trim().is_empty() && !is_list_line(lines[i]) {
        prompt_lines.push(lines[i].trim().to_string());
        i += 1;
    }
    while i < lines.len() && lines[i].trim().is_empty() {
        i += 1;
    }

    let mut options: Vec<DecisionOption> = Vec::new();
    // Options drawn as code are an example, not answers.
    while i < lines.len() && !code[i] && is_list_line(lines[i]) {
        // Every item must start with a bold letter or number, or this list is not the options.
        let (letter, text) = option_line(lines[i])?;
        let stripped = without_recommended(&text).map(|head| head.trim().to_string());
        let recommended = stripped.is_some();
        let text = stripped.unwrap_or(text);
        options.push(DecisionOption {
            letter,
            number: options.len() as u32 + 1,
            text,
            recommended,
        });
        i += 1;
    }
    if options.len() < 2 {
        return None;
    }

    Some(Decision {
        before: lines[..head_index].join("\n").trim().to_string(),
        prompt: prompt_lines.join(" ").trim().to_string(),
        options,
        after: lines[i..].join("\n").trim().to_string(),
    })
}

/// The comment a tap on a card posts. Options are numbered in order, whatever marker the asker
/// wrote, and the reply leads with the number.
pub fn reply(option: &DecisionOption) -> String {
    if option.text.is_empty() {
        option.number.to_string()
    } else {
        format!("{} — {}", option.number, option.text)
    }
}

/// The number of the option a reply picks: the number it starts with, or the marker the asker
/// wrote, alone or followed by a space or punctuation.
///
/// `2 — Wait`, `1. go`, `b` and `C — Something else` choose. `2nd thoughts` and `10 minutes` with
/// no tenth option do not, and neither does `Béatrice doit vérifier`: the lead has to end at
/// something that is not a letter or a number **in any script**, or every word beginning with a
/// Latin letter would answer the question.
pub fn chosen_number(reply: &str, options: &[DecisionOption]) -> Option<u32> {
    let body = reply.trim_start();
    let lead: String = body
        .chars()
        .take_while(|c| c.is_ascii_alphanumeric())
        .collect();
    if lead.is_empty() {
        return None;
    }
    if body[lead.len()..]
        .chars()
        .next()
        .is_some_and(char::is_alphanumeric)
    {
        return None;
    }
    if lead.chars().all(|c| c.is_ascii_digit()) {
        let number: u32 = lead.parse().ok()?;
        return options
            .iter()
            .any(|option| option.number == number)
            .then_some(number);
    }
    let upper = lead.to_uppercase();
    options
        .iter()
        .find(|option| option.letter == upper)
        .map(|option| option.number)
}

// ---------------------------------------------------------------------------------------------
// The line shapes the parser reads
// ---------------------------------------------------------------------------------------------

/// `^\*\*Decision:\*\*\s*(.*)$` over an already-trimmed line: the prompt's first line.
fn decision_head(trimmed: &str) -> Option<&str> {
    Some(trimmed.strip_prefix("**Decision:**")?.trim_start())
}

/// `^\s*(?:[-*+]|\d+[.)])\s+` — what is left of a line after its list marker, or `None` when it
/// carries none.
fn strip_list_prefix(line: &str) -> Option<&str> {
    let body = line.trim_start();
    let rest = match body.strip_prefix(['-', '*', '+']) {
        Some(rest) => rest,
        None => {
            let digits = body.chars().take_while(char::is_ascii_digit).count();
            if digits == 0 {
                return None;
            }
            body[digits..].strip_prefix(['.', ')'])?
        }
    };
    // `\s+`: at least one, and the match takes the whole run.
    rest.starts_with(char::is_whitespace)
        .then(|| rest.trim_start())
}

fn is_list_line(line: &str) -> bool {
    strip_list_prefix(line).is_some()
}

/// An option item's marker and its text — the TypeScript's
/// `(?:\*\*([A-Za-z]|\d{1,2})(?:[.):])?\*\*[.):]?)\s*(.*)$` after the list marker.
///
/// The punctuation may sit inside the bold (`**A.**`), just after it (`**A**.`) or not be there at
/// all (`**A**`); the optional group is greedy, so the inside is tried first.
fn option_line(line: &str) -> Option<(String, String)> {
    let body = strip_list_prefix(line)?;
    let after_bold = body.strip_prefix("**")?;
    for &marker in marker_lengths(after_bold)? {
        let letter = &after_bold[..marker];
        let rest = &after_bold[marker..];
        let inside = rest.strip_prefix(['.', ')', ':']).unwrap_or(rest);
        for candidate in [inside, rest] {
            if let Some(tail) = candidate.strip_prefix("**") {
                let text = tail.strip_prefix(['.', ')', ':']).unwrap_or(tail);
                return Some((letter.to_uppercase(), text.trim().to_string()));
            }
        }
    }
    None
}

/// `\s*\(recommended\)\s*$`, case-insensitively: what is left of an option's text without it, or
/// `None` when it does not end that way.
fn without_recommended(text: &str) -> Option<&str> {
    const TOKEN: &str = "(recommended)";
    let end = text.trim_end();
    let cut = end.len().checked_sub(TOKEN.len())?;
    if !end.is_char_boundary(cut) {
        return None;
    }
    let (head, tail) = end.split_at(cut);
    tail.eq_ignore_ascii_case(TOKEN).then_some(head)
}

/// Leading whitespace in columns, a tab running to the next multiple of four.
fn indent_width(line: &str) -> usize {
    let mut width = 0;
    for ch in line.chars() {
        match ch {
            ' ' => width += 1,
            '\t' => width += 4 - (width % 4),
            _ => break,
        }
    }
    width
}

/// The fence a line opens, or `None`.
///
/// A fence may open inside a list item (`` - ```markdown ``), and a backtick fence's info string
/// cannot hold a backtick — which is what makes a one-line ```` ```span``` ```` not a fence.
fn fence_opener(line: &str) -> Option<String> {
    let (body, after_marker) = match strip_list_prefix(line) {
        Some(body) => (body, true),
        None => (line, false),
    };
    // Without a list marker in front, four columns of indent makes it code, not a fence.
    if !after_marker && indent_width(line) >= 4 {
        return None;
    }
    let trimmed = body.trim_start();
    let run = fence_run(trimmed)?;
    if run.starts_with('`') && trimmed[run.len()..].contains('`') {
        return None;
    }
    Some(run)
}

/// The fence a line closes, or `None`: `^(`{3,}|~{3,})\s*$` over the trimmed line, which is a
/// fence run with nothing after it.
fn fence_close(trimmed: &str) -> Option<String> {
    let run = fence_run(trimmed)?;
    trimmed[run.len()..].trim().is_empty().then_some(run)
}

/// The run of three or more backticks or tildes a string starts with.
fn fence_run(text: &str) -> Option<String> {
    let first = text.chars().next()?;
    if first != '`' && first != '~' {
        return None;
    }
    let run: String = text.chars().take_while(|c| *c == first).collect();
    (run.len() >= 3).then_some(run)
}

/// Which lines markdown draws as code: inside a ``` or ~~~ fence, or indented four columns.
///
/// A Decision written there is an example of the format, not a question somebody is asking, and
/// answering it would post a comment nobody wanted.
fn code_lines(lines: &[&str]) -> Vec<bool> {
    let mut code = vec![false; lines.len()];
    let mut fence: Option<String> = None;
    for (i, line) in lines.iter().enumerate() {
        if let Some(open) = &fence {
            code[i] = true;
            // A fence closes on its own character, at its own length or longer.
            if let Some(close) = fence_close(line.trim()) {
                if close.starts_with(open.chars().next().unwrap_or('`'))
                    && close.len() >= open.len()
                {
                    fence = None;
                }
            }
            continue;
        }
        if let Some(open) = fence_opener(line) {
            fence = Some(open);
            code[i] = true;
            continue;
        }
        // Indented code cannot interrupt a paragraph, so it needs a blank line or more code above.
        let after_break = i == 0 || lines[i - 1].trim().is_empty() || code[i - 1];
        if !line.trim().is_empty() && indent_width(line) >= 4 && after_break {
            code[i] = true;
        }
    }
    code
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn markers_for_a_grid_row_as_the_web_reads_them_awtd_1626() {
        assert_eq!(punctuated_marker_len("A. Lisbon"), Some(3));
        assert_eq!(punctuated_marker_len("12) x"), Some(4));
        assert_eq!(punctuated_marker_len("2)"), Some(2));
        assert_eq!(punctuated_marker_len("A.Lisbon"), None);
        assert_eq!(punctuated_marker_len("123. x"), None);
        assert_eq!(punctuated_marker_len("I am"), None);
        assert!(is_bare_marker(" B "));
        assert!(is_bare_marker("12:"));
        assert!(!is_bare_marker("Bo"));
        assert!(!is_bare_marker("123"));
    }
}
